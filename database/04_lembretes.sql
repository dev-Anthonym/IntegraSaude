-- Módulo Lembretes e Alertas (Pessoa 4)
-- Depende das tabelas usuario (Pessoa 1), medicamento (Pessoa 2) e consulta (Pessoa 3)

CREATE TABLE IF NOT EXISTS lembrete (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id      BIGINT       NOT NULL,
    tipo             VARCHAR(20)  NOT NULL,
    medicamento_id   BIGINT,
    consulta_id      BIGINT,
    descricao        VARCHAR(150) NOT NULL,
    horario_previsto TIMESTAMP    NOT NULL,
    status           VARCHAR(20)  DEFAULT 'PENDENTE' NOT NULL,
    alerta_enviado   BOOLEAN      DEFAULT FALSE NOT NULL,
    CONSTRAINT fk_lembrete_paciente    FOREIGN KEY (paciente_id)    REFERENCES usuario (id),
    CONSTRAINT fk_lembrete_medicamento FOREIGN KEY (medicamento_id) REFERENCES medicamento (id),
    CONSTRAINT fk_lembrete_consulta    FOREIGN KEY (consulta_id)    REFERENCES consulta (id),
    -- RN01: origem e status permitidos
    CONSTRAINT ck_lembrete_tipo   CHECK (tipo IN ('MEDICAMENTO', 'CONSULTA')),
    CONSTRAINT ck_lembrete_status CHECK (status IN ('PENDENTE', 'CONFIRMADO', 'PERDIDO')),
    -- Apenas um entre medicamento_id e consulta_id, coerente com o tipo
    CONSTRAINT ck_lembrete_item CHECK (
        (tipo = 'MEDICAMENTO' AND medicamento_id IS NOT NULL AND consulta_id IS NULL)
        OR (tipo = 'CONSULTA' AND consulta_id IS NOT NULL AND medicamento_id IS NULL)
    ),
    -- RN07: alerta só existe para lembrete perdido
    CONSTRAINT ck_lembrete_alerta CHECK (alerta_enviado = FALSE OR status = 'PERDIDO'),
    -- RN08: sem lembretes duplicados para o mesmo item e horário
    CONSTRAINT uq_lembrete_medicamento_horario UNIQUE (medicamento_id, horario_previsto),
    CONSTRAINT uq_lembrete_consulta_horario    UNIQUE (consulta_id, horario_previsto)
);

CREATE INDEX IF NOT EXISTS idx_lembrete_paciente_status ON lembrete (paciente_id, status);

-- RN09: histórico de eventos de cada lembrete
CREATE TABLE IF NOT EXISTS historico (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lembrete_id BIGINT      NOT NULL,
    tipo_evento VARCHAR(20) NOT NULL,
    data_hora   TIMESTAMP   NOT NULL,
    CONSTRAINT fk_historico_lembrete FOREIGN KEY (lembrete_id) REFERENCES lembrete (id),
    CONSTRAINT ck_historico_tipo CHECK (tipo_evento IN ('GERADO', 'CONFIRMADO', 'PERDIDO', 'ALERTA_ENVIADO'))
);

CREATE INDEX IF NOT EXISTS idx_historico_lembrete_data ON historico (lembrete_id, data_hora);
